def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--pattern",
        action="append",
        dest="patterns",
        help="glob relative to repo root; may be repeated",
    )
    parser.add_argument("--capabilities", default=DEFAULT_CAPABILITIES)
    parser.add_argument("--summary-json", default=DEFAULT_SUMMARY)
    parser.add_argument("--markdown", default=DEFAULT_MARKDOWN)
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    patterns = tuple(args.patterns or DEFAULT_PATTERNS)
    artifacts = discover_artifacts(ROOT, patterns)
    report = build_report(
        root=ROOT,
        artifact_paths=artifacts,
        capability_path=ROOT / args.capabilities,
        patterns=patterns,
    )

    summary_path = ROOT / args.summary_json
    markdown_path = ROOT / args.markdown
    summary_path.parent.mkdir(parents=True, exist_ok=True)
    markdown_path.parent.mkdir(parents=True, exist_ok=True)
    summary_path.write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    markdown_path.write_text(render_markdown(report), encoding="utf-8")

    if args.json:
        print(json.dumps(report, sort_keys=True))
    else:
        print("fleetrmw-unified-benchmark-report")
        print(f"  status: {report['status']}")
        print(f"  artifacts: {report['artifact_count']}")
        print(f"  summary: {args.summary_json}")
        print(f"  markdown: {args.markdown}")
    return 0 if report["status"] in {"ok", "partial"} else 1


def discover_artifacts(root: Path, patterns: Iterable[str]) -> list[Path]:
    paths: set[Path] = set()
    for pattern in patterns:
        paths.update(root.glob(pattern))
    return sorted(
        path
        for path in paths
        if path.is_file()
        and path.name != Path(DEFAULT_SUMMARY).name
        and not path.name.startswith("unified_benchmark_report")
    )


def build_report(
    *,
    root: Path,
    artifact_paths: Iterable[Path],
    capability_path: Path,
    patterns: Iterable[str],
) -> dict[str, Any]:
    artifacts = [
        summarize_artifact(root=root, path=path)
        for path in sorted(artifact_paths)
    ]
    ok = sum(1 for artifact in artifacts if artifact["status"] == "ok")
    failed = sum(1 for artifact in artifacts if artifact["status"] == "failed")
    partial = sum(1 for artifact in artifacts if artifact["status"] == "partial")
    unknown = sum(1 for artifact in artifacts if artifact["status"] == "unknown")
    status = "ok" if artifacts and failed == 0 and partial == 0 and unknown == 0 else "partial"
    if not artifacts or ok == 0:
        status = "failed"
    capabilities = summarize_capabilities(capability_path)
    claim_boundaries = {
        key: capabilities.get("claim_boundaries", {}).get(key)
        for key in CLAIM_BOUNDARY_KEYS
        if key in capabilities.get("claim_boundaries", {})
    }
    return {
        "schema_version": SCHEMA_VERSION,
        "status": status,
        "artifact_history_status": status,
        "artifact_status_scope": "all_discovered_artifacts_including_retained_historical_runs",
        "artifact_status_note": (
            "Retained debug, smoke, negative-control, superseded, and canonical artifacts "
            "all contribute to this status; failures are not filtered from the report."
        ),
        "patterns": list(patterns),
        "artifact_count": len(artifacts),
        "ok_artifact_count": ok,
        "partial_artifact_count": partial,
        "failed_artifact_count": failed,
        "unknown_artifact_count": unknown,
        "capability_manifest": capabilities,
        "capability_manifest_status": capabilities.get("status", "unknown"),
        "claim_boundary_true_count": sum(value is True for value in claim_boundaries.values()),
        "claim_boundary_false_count": sum(value is False for value in claim_boundaries.values()),
        "claim_boundary_summary": claim_boundaries,
        "artifacts": artifacts,
    }


def summarize_artifact(*, root: Path, path: Path) -> dict[str, Any]:
    relative_path = path.relative_to(root).as_posix() if path.is_relative_to(root) else str(path)
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        return {
            "path": relative_path,
            "category": classify_path(path, {}),
            "schema_version": "unreadable",
            "status": "failed",
            "reason": str(exc),
            "run_count": 0,
            "ok_run_count": 0,
            "failed_run_count": 1,
            "metrics": {},
        }
    status = normalize_status(data.get("status"))
    rows = rows_for(data)
    run_count = first_int(data, "run_count", "row_count") or len(rows)
    ok_run_count = (
        first_int(data, "ok_run_count", "passed_run_count", "ok_row_count")
        or count_rows(rows, "ok")
    )
    failed_run_count = (
        first_int(data, "failed_run_count", "failed_row_count")
        or count_failed_rows(rows)
    )
    return {
        "path": relative_path,
        "category": classify_path(path, data),
        "schema_version": str(data.get("schema_version", "unknown")),
        "status": status,
        "reason": str(data.get("reason", data.get("stage", ""))),
        "run_count": run_count,
        "ok_run_count": ok_run_count,
        "failed_run_count": failed_run_count,
        "metrics": extract_metrics(data),
    }


