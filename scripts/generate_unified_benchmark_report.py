def normalize_status(value: Any) -> str:
    if value in {"ok", "partial", "failed", "unknown"}:
        return str(value)
    if value is True:
        return "ok"
    if value is False:
        return "failed"
    return "unknown"


def rows_for(data: dict[str, Any]) -> list[dict[str, Any]]:
    for key in ("runs", "rows", "results"):
        rows = data.get(key)
        if isinstance(rows, list):
            return [row for row in rows if isinstance(row, dict)]
    return []


def count_rows(rows: list[dict[str, Any]], status: str) -> int:
    return sum(1 for row in rows if row.get("status") == status)


def count_failed_rows(rows: list[dict[str, Any]]) -> int:
    return sum(1 for row in rows if normalize_status(row.get("status")) == "failed")


def first_int(data: dict[str, Any], *keys: str) -> int:
    for key in keys:
        value = data.get(key)
        if value is None:
            continue
        try:
            return int(value)
        except (TypeError, ValueError):
            continue
    return 0


def extract_metrics(data: dict[str, Any]) -> dict[str, Any]:
    metrics: dict[str, Any] = {}
    for key in METRIC_KEYS:
        if key in data:
            metrics[key] = data[key]
    probe = data.get("probe")
    if isinstance(probe, dict):
        for key in METRIC_KEYS:
            if key not in metrics and key in probe:
                metrics[key] = probe[key]
    aggregates = data.get("aggregates")
    if isinstance(aggregates, dict):
        metrics["aggregate_system_count"] = len(aggregates)
        metrics["aggregate_systems"] = sorted(str(key) for key in aggregates)
    elif isinstance(aggregates, list):
        systems = sorted(
            {
                str(row.get("system"))
                for row in aggregates
                if isinstance(row, dict) and row.get("system")
            }
        )
        metrics["aggregate_row_count"] = len(aggregates)
        metrics["aggregate_system_count"] = len(systems)
        metrics["aggregate_systems"] = systems
    return metrics


def render_markdown(report: dict[str, Any]) -> str:
    capabilities = report.get("capability_manifest", {})
    lines = [
        "# FleetRMW unified benchmark report",
        "",
        f"- schema: `{report['schema_version']}`",
        f"- all-artifact history status: `{report['artifact_history_status']}`",
        f"- artifact status scope: `{report['artifact_status_scope']}`",
        f"- status note: {report['artifact_status_note']}",
        f"- artifacts: `{report['artifact_count']}` "
        f"(ok `{report['ok_artifact_count']}`, partial `{report['partial_artifact_count']}`, "
        f"failed `{report['failed_artifact_count']}`, unknown `{report['unknown_artifact_count']}`)",
        f"- implementation: `{capabilities.get('implementation', 'unknown')}`",
        f"- current capability manifest status: `"
        f"{report.get('capability_manifest_status', 'unknown')}`",
        f"- production_ready: `{str(capabilities.get('production_ready')).lower()}`",
        f"- serialization_format: `{capabilities.get('serialization_format', 'unknown')}`",
        f"- explicit claim boundaries: true `{report.get('claim_boundary_true_count', 0)}`, "
        f"false `{report.get('claim_boundary_false_count', 0)}`",
        "",
        "## Claim boundaries",
        "",
    ]
    for key, value in report.get("claim_boundary_summary", {}).items():
        lines.append(f"- `{key}`: `{str(value).lower()}`")
    unsupported = capabilities.get("unsupported", [])
    if unsupported:
        lines.extend([
            "",
            "Unsupported surfaces kept explicit:",
            "",
            ", ".join(f"`{item}`" for item in unsupported),
        ])
    lines.extend([
        "",
        "## Artifacts",
        "",
        "| Category | Status | Runs | OK | Failed | Schema | Artifact | Key metrics |",
        "| --- | --- | ---: | ---: | ---: | --- | --- | --- |",
    ])
    for artifact in report.get("artifacts", []):
        metrics = format_metrics(artifact.get("metrics", {}))
        lines.append(
            "| "
            f"{artifact['category']} | "
            f"`{artifact['status']}` | "
            f"{artifact['run_count']} | "
            f"{artifact['ok_run_count']} | "
            f"{artifact['failed_run_count']} | "
            f"`{artifact['schema_version']}` | "
            f"`{artifact['path']}` | "
            f"{metrics} |"
        )
    lines.append("")
    return "\n".join(lines)


def format_metrics(metrics: dict[str, Any]) -> str:
    if not metrics:
        return ""
    parts: list[str] = []
    for key in sorted(metrics):
        value = metrics[key]
        if isinstance(value, list):
            text = ",".join(str(item) for item in value[:6])
            if len(value) > 6:
                text += ",..."
        elif isinstance(value, dict):
            text = f"{len(value)} entries"
        else:
            text = str(value)
        parts.append(f"`{key}={text}`")
    return "<br>".join(parts)


